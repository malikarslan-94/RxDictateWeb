/**
 * Copies the API contract from clinic-api into src/contract.
 *
 * clinic-api/src/shared is the single source of truth for every shape that
 * crosses the wire (zod schemas, error codes, roles). The web app keeps a copy
 * rather than importing across folders, so a build only ever sees this repo.
 * The mobile app (clinic-app) keeps the same copy. Run after any change to the
 * API contract:
 *
 *   yarn sync:contract            (expects ../clinic-api)
 *   CONTRACT_SRC=/path/to/shared yarn sync:contract
 */
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(
  process.env.CONTRACT_SRC ?? join(root, '../clinic-api/src/shared'),
);
const target = join(root, 'src/contract');

if (!existsSync(source)) {
  console.error(`Contract source not found: ${source}`);
  process.exit(1);
}

const header =
  '// GENERATED by scripts/sync-contract.mjs from clinic-api/src/shared.\n' +
  '// Do not edit here: change the API contract, then run `yarn sync:contract`.\n\n';

rmSync(target, { recursive: true, force: true });
mkdirSync(target, { recursive: true });

const files = readdirSync(source).filter((name) => name.endsWith('.ts'));
for (const name of files) {
  writeFileSync(
    join(target, name),
    header + readFileSync(join(source, name), 'utf8'),
  );
}

console.log(`Synced ${files.length} contract files into src/contract`);
